const UNGA_TITLE = "UN General Assembly 81";

function ac(
  partial: Omit<Aircraft, "note"> & { note?: string },
): Aircraft {
  return {
    note: "Known VIP airframe. Transponder often dark in flight.",
    imageUrl: `/craft/${partial.id}.webp`,
    ...partial,
  };
}

function ungaTrip(
  id: string,
  depart: { t: string; place: typeof P.jfk },
  arriveT: string,
  stayUntil: string,
  retDep: string,
  retArr: string,
  aircraftId: string,
  confidence: "official" | "reported" | "modeled" = "official",
): Leader["trips"][number] {
  return {
    id,
    title: UNGA_TITLE,
    kind: "unga",
    source: "schedule",
    confidence,
    depart,
    arrive: { t: arriveT, place: P.jfk },
    venue: "UN Headquarters",
    stayUntil,
    returnDepart: retDep,
    returnArrive: retArr,
    aircraftId,
  };
}

